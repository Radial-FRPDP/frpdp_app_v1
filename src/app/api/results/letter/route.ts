import { NextRequest, NextResponse } from "next/server";
import { PDFDocument, StandardFonts, rgb } from "pdf-lib";
import { createServerSupabaseClient, createServiceRoleClient } from "@/lib/supabase/server";
import type { SubjectScore } from "@/lib/database.types";

export const runtime = "nodejs";

/**
 * Candidate M-04 result letter (see design-reference-gap-analysis.md
 * Section 3.6). Generated on demand from exam_results + candidates data
 * rather than pre-rendered and stored -- there's no storage bucket or
 * "generate" step to keep in sync, this route just is the generator.
 *
 * Gated on exam_results.result_approved_at (migration 0013), set by
 * Radial Circle on the M-04 Results tab -- an unsubmitted or
 * PM-unapproved result has nothing to download yet.
 */
export async function GET(_req: NextRequest) {
  const authed = await createServerSupabaseClient();
  const {
    data: { user },
  } = await authed.auth.getUser();
  if (!user) {
    return NextResponse.json({ error: "Not authenticated" }, { status: 401 });
  }

  const db = createServiceRoleClient();
  const { data: candidate } = await db
    .from("candidates")
    .select("id, full_name, jqs_number, discipline")
    .eq("auth_user_id", user.id)
    .maybeSingle();
  if (!candidate) {
    return NextResponse.json({ error: "No candidate profile linked to this account" }, { status: 404 });
  }

  const { data: result } = await db
    .from("exam_results")
    .select("subject_scores, total_score, max_score, passed, result_approved_at")
    .eq("candidate_id", candidate.id)
    .maybeSingle();

  if (!result || !result.result_approved_at) {
    return NextResponse.json({ error: "Your result letter isn't ready yet — it's released once Radial Circle approves your result." }, { status: 403 });
  }

  const pdf = await PDFDocument.create();
  const page = pdf.addPage([595.28, 841.89]); // A4
  const bold = await pdf.embedFont(StandardFonts.HelveticaBold);
  const regular = await pdf.embedFont(StandardFonts.Helvetica);

  const green = rgb(0x05 / 255, 0x88 / 255, 0x12 / 255);
  const navy = rgb(0x1b / 255, 0x4f / 255, 0x8a / 255);
  const dark = rgb(0x32 / 255, 0x32 / 255, 0x32 / 255);
  const grey = rgb(0x64 / 255, 0x64 / 255, 0x64 / 255);

  let y = 780;
  page.drawRectangle({ x: 0, y: 800, width: 595.28, height: 41.89, color: green });
  page.drawText("Field Readiness Programme", { x: 40, y: 816, size: 16, font: bold, color: rgb(1, 1, 1) });
  page.drawText("2025 Cohort — CBT Result Letter", { x: 40, y: 802, size: 10, font: regular, color: rgb(1, 1, 1) });

  y = 760;
  const line = (label: string, value: string) => {
    page.drawText(label, { x: 40, y, size: 10, font: regular, color: grey });
    page.drawText(value, { x: 180, y, size: 11, font: bold, color: dark });
    y -= 22;
  };
  y -= 20;
  line("Candidate Name", candidate.full_name);
  line("JQS Number", candidate.jqs_number ?? "—");
  line("Discipline", candidate.discipline ?? "—");
  line("Result Approved", new Date(result.result_approved_at).toLocaleDateString("en-GB", { day: "numeric", month: "long", year: "numeric" }));

  y -= 20;
  const pct = result.max_score > 0 ? Math.round((result.total_score / result.max_score) * 100) : 0;
  page.drawText(`Overall Score: ${result.total_score} / ${result.max_score} (${pct}%)`, { x: 40, y, size: 13, font: bold, color: dark });
  y -= 20;
  page.drawText(result.passed ? "RESULT: PASSED" : "RESULT: NOT PASSED", {
    x: 40,
    y,
    size: 16,
    font: bold,
    color: result.passed ? green : rgb(0x9b / 255, 0x23 / 255, 0x35 / 255),
  });

  y -= 40;
  page.drawText("Subject Breakdown", { x: 40, y, size: 11, font: bold, color: navy });
  y -= 20;
  const subjectScores = (result.subject_scores ?? []) as SubjectScore[];
  for (const s of subjectScores) {
    const spct = s.maxScore > 0 ? Math.round((s.score / s.maxScore) * 100) : 0;
    page.drawText(s.subject, { x: 50, y, size: 10, font: regular, color: dark });
    page.drawText(`${s.score} / ${s.maxScore} (${spct}%)`, { x: 320, y, size: 10, font: regular, color: dark });
    y -= 18;
  }

  y -= 20;
  page.drawText("This letter is generated by the Field Readiness Programme platform and reflects", { x: 40, y, size: 8, font: regular, color: grey });
  y -= 12;
  page.drawText("the result on file as approved by the Programme Manager.", { x: 40, y, size: 8, font: regular, color: grey });

  const bytes = await pdf.save();
  return new NextResponse(Buffer.from(bytes), {
    headers: {
      "Content-Type": "application/pdf",
      "Content-Disposition": `attachment; filename="result-letter-${candidate.jqs_number ?? candidate.id.slice(0, 8)}.pdf"`,
    },
  });
}
